#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <random>
#include <string>


// Writes GeneratedCases.inc for CompareGenerated.cpp: one GENERATED line for each pattern of a fixed-seed grammar. Patterns must be
// compile-time arguments, so the list is written before the test is compiled. The grammar uses only what the parser accepts: quantifiers
// follow atoms and groups, never anchors, and each atom takes one quantifier with an optional lazy ?. The last number on a line is 1
// the comparison mode: 0 for every check, 1 when a quantified body can match the empty string, and 2 when a quantified body holds a capture
// group. CompareGenerated.cpp explains the two skipped modes.


namespace {


constexpr int PatternCount = 5000;
constexpr std::uint32_t Seed = 20261122;
constexpr int MaxGroups = 6;


struct Piece {
	std::string text;
	bool nullable;
	bool captures;
};


class Grammar {
private:
	std::mt19937 rng;
	int groups = 0;
	int mode = 0;


public:
	explicit Grammar(std::uint32_t seed) : rng(seed) {
	}


	void Start() {
		groups = 0;
		mode = 0;
	}


	// 0: every check. 1: a quantified body can match the empty string. 2: a quantified body holds a capture group.
	int Mode() const {
		return mode;
	}


	Piece Pattern() {
		return Alternation(0);
	}


private:
	int Roll(int bound) {
		return static_cast<int>(rng() % static_cast<std::uint32_t>(bound));
	}


	Piece Alternation(int depth) {
		int count = Roll(100) < 20 ? 2 + Roll(2) : 1;
		Piece result{"", false, false};
		for (int index = 0; index < count; index++) {
			Piece branch = Sequence(depth);
			if (index > 0) {
				result.text += "|";
				result.nullable = result.nullable || branch.nullable;
			} else {
				result.nullable = branch.nullable;
			}

			result.captures = result.captures || branch.captures;
			result.text += branch.text;
		}

		return result;
	}


	Piece Sequence(int depth) {
		if (Roll(100) < 8) {
			return Piece{"", true, false};
		}

		int items = 1 + Roll(4);
		Piece result{"", true, false};
		for (int index = 0; index < items; index++) {
			Piece item = Term(depth);
			result.text += item.text;
			result.nullable = result.nullable && item.nullable;
			result.captures = result.captures || item.captures;
		}

		return result;
	}


	Piece Term(int depth) {
		int roll = Roll(100);
		if (roll < 12) {
			return Piece{Roll(2) == 0 ? "^" : "$", true, false};
		}

		if (roll < 24 && depth < 3 && groups < MaxGroups) {
			groups++;
			Piece inner = Alternation(depth + 1);
			return Quantified("(" + inner.text + ")", inner.nullable, true);
		}

		if (roll < 32 && depth < 3) {
			Piece inner = Alternation(depth + 1);
			return Quantified("(?:" + inner.text + ")", inner.nullable, inner.captures);
		}

		static const char* const atoms[8] = {"a", "b", ".", "[ab]", "[^a]", "\\d", "\\w", "\\s"};
		return Quantified(atoms[Roll(8)], false, false);
	}


	Piece Quantified(const std::string& body, bool bodyNullable, bool bodyCaptures) {
		int roll = Roll(100);
		std::string quantifier;
		bool minimumZero = false;
		if (roll < 55) {
			quantifier = "";
		} else if (roll < 65) {
			quantifier = "*";
			minimumZero = true;
		} else if (roll < 75) {
			quantifier = "+";
		} else if (roll < 85) {
			quantifier = "?";
			minimumZero = true;
		} else {
			quantifier = "{1,2}";
		}

		if (!quantifier.empty() && bodyNullable) {
			mode = 1;
		} else if (!quantifier.empty() && bodyCaptures && mode == 0) {
			mode = 2;
		}

		bool lazy = !quantifier.empty() && Roll(100) < 25;
		Piece result{body + quantifier + (lazy ? "?" : ""), bodyNullable || minimumZero, bodyCaptures};
		if (quantifier.empty()) {
			result.nullable = bodyNullable;
		}

		return result;
	}
};


}


// Usage: GenerateCases <part> <parts>. The grammar runs through all the patterns in order, so every part sees the same patterns, and the
// part writes the patterns whose index is <part> modulo <parts>. Each part is compiled as its own translation unit, because the template
// instantiations of 5,000 patterns take too long in one.
int main(int argc, char** argv) {
	if (argc != 3) {
		std::printf("usage: GenerateCases <part> <parts>\n");
		return 2;
	}

	int part = std::atoi(argv[1]);
	int parts = std::atoi(argv[2]);
	if (parts <= 0 || part < 0 || part >= parts) {
		std::printf("usage: GenerateCases <part> <parts>, with 0 <= part < parts\n");
		return 2;
	}

	Grammar grammar(Seed);
	std::printf("// Generated by GenerateCases.cpp with seed %u, %d patterns, part %d of %d. Do not edit.\n", static_cast<unsigned>(Seed), PatternCount, part, parts);
	for (int index = 0; index < PatternCount; index++) {
		grammar.Start();
		Piece pattern = grammar.Pattern();
		if (index % parts == part) {
			std::printf("GENERATED(%d, R\"(%s)\", %d)\n", index, pattern.text.c_str(), grammar.Mode());
		}
	}

	return 0;
}
