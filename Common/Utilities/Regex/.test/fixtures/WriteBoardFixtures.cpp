// Escapes a text for a C++ string literal: the backslash and the double quote.
std::string Quote(std::string_view text) {
	std::string quoted = "\"";
	for (char character : text) {
		if (character == '\\' || character == '"') {
			quoted.push_back('\\');
		}

		quoted.push_back(character);
	}

	quoted.push_back('"');
	return quoted;
}


std::regex::flag_type FlagsOf(const Pattern& pattern) {
	std::regex::flag_type flags = std::regex::ECMAScript;
	if (pattern.ignoreCase) {
		flags |= std::regex::icase;
	}

	return flags;
}


// The text of a group of the first match, or empty when the group did not take part.
std::string GroupText(const std::smatch& match, std::size_t group) {
	if (group >= match.size() || !match[group].matched) {
		return std::string();
	}

	return match[group].str();
}


